-- 1. Create Profiles Table (Public User Data)
-- This table mirrors auth.users to allow admin to view user lists
create table if not exists public.profiles (
  id uuid references auth.users not null primary key,
  email text,
  full_name text,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 2. Trigger to auto-create profile on signup
-- Enable this to automatically populate profiles when a user signs up
create or replace function public.handle_new_user() 
returns trigger as $$
begin
  insert into public.profiles (id, email, full_name, created_at)
  values (new.id, new.email, new.raw_user_meta_data->>'full_name', new.created_at);
  return new;
end;
$$ language plpgsql security definer;

-- Trigger creation (safe to run multiple times if dropped first, but IF NOT EXISTS is harder for triggers)
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

