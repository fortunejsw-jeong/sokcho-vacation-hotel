-- 4. Review Bookings Table (Ensure it exists)
create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  user_id uuid references auth.users not null,
  room_id bigint references public.rooms not null,
  check_in date not null,
  check_out date not null,
  guests integer default 2,
  total_price integer,
  status text default 'pending', -- pending, confirmed, cancelled
  payment_status text default 'unpaid'
);

-- 5. Add 'images' column to Rooms table (for dynamic gallery)
do $$ 
begin 
  if not exists (select 1 from information_schema.columns where table_name = 'rooms' and column_name = 'images') then
    alter table public.rooms add column images jsonb;
  end if;
end $$;
